// Usage: node packages/api/scripts/build-partner-localities.mjs <cities.zip> <subdivisions.zip>
// Natural Earth public-domain 1:10m populated places (simple, v5.1.2) and admin-1 (v5.1.1).
// https://www.naturalearthdata.com/downloads/10m-cultural-vectors/10m-populated-places/
// https://www.naturalearthdata.com/downloads/10m-cultural-vectors/10m-admin-1-states-provinces/
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

function* table(archive) {
  const data = execFileSync("unzip", ["-p", archive, "*.dbf"], { maxBuffer: 64 * 1024 * 1024 });
  const rows = data.readUInt32LE(4);
  const header = data.readUInt16LE(8);
  const stride = data.readUInt16LE(10);
  const fields = new Map();
  let offset = 1;
  for (let i = 32; i + 32 <= header; i += 32) {
    const name = data.toString("ascii", i, i + 11).split("\0")[0];
    const length = data[i + 16];
    fields.set(name, [offset, length]);
    offset += length;
  }
  for (let index = 0; index < rows; index++) {
    const row = header + index * stride;
    if (data[row] === 42) continue;
    yield (name) => {
      const [start, length] = fields.get(name);
      return data.toString("utf8", row + start, row + start + length).replace(/\0/gu, "").trim();
    };
  }
}

const key = (name) => name.normalize("NFD").replace(/\p{M}/gu, "").toLowerCase()
  .replace(/[^\p{L}\p{N}]+/gu, " ").trim();
function collect(archive, columns) {
  const byCountry = new Map();
  for (const row of table(archive)) {
    const country = row("iso_a2");
    if (!/^[A-Z]{2}$/u.test(country)) continue;
    const names = byCountry.get(country) ?? new Set();
    for (const column of columns) {
      const name = key(row(column));
      if (name.length >= 3 && /\p{L}/u.test(name)) names.add(name);
    }
    if (names.size) byCountry.set(country, names);
  }
  return Object.fromEntries([...byCountry.keys()].sort().map((country) => [country, [...byCountry.get(country)].sort().join("|")]));
}

const [cities, subdivisions] = process.argv.slice(2);
if (!cities || !subdivisions) throw Error("Provide the Natural Earth cities and subdivisions ZIP archives.");
const output = new URL("../src/partner-locality-data.ts", import.meta.url);
const declarations = [
  "// Generated by packages/api/scripts/build-partner-localities.mjs from Natural Earth public-domain data.",
  `export const CITIES_BY_COUNTRY = ${JSON.stringify(collect(cities, ["name", "nameascii"]), null, 2)};`,
  `export const SUBDIVISIONS_BY_COUNTRY = ${JSON.stringify(collect(subdivisions, ["name", "name_en"]), null, 2)};`,
];
writeFileSync(output, declarations.join("\n\n") + "\n");
